#!/usr/bin/env python3
"""Write detector/export_spec.json: what the trained SPLICE detector export must supply.

    python3 tools/make_export_spec.py            # write
    python3 tools/make_export_spec.py --check    # exit 1 if the file is stale

The spec is derived from the manifest so it cannot drift from it: every manifest field
that the dev-synthetic profile fills with a synthetic value (SYN-xx) or a design decision
(DD-xx), and every field still null, becomes an export item; the learned tensors the
paper names but does not list as values (roadmap 2.1) are added with their shapes and the
dispatcher unit that consumes them.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO / "tools"))

from svgen.manifest import load_manifest, manifest_sha256, null_fields  # noqa: E402

OUT = REPO / "detector" / "export_spec.json"

# Learned maps of arm (e) that are model weights, not manifest scalars (roadmap 2.1, SPLICE-V Eq. (3)/(5)).
# Shapes use the paper's geometry: C = 64 latent channels, Ct = 48 transported, D_K = 64 key width,
# J = 12 descriptor entries (4 bands x 3 levels), D_U = forecast compatibility width.
TENSORS = [
    {"name": "hypothesis_head", "role": "anchor box hypotheses (mu, precision) used by the conformal gate", "shape": "per anchor: 4 means + 4 precisions",
     "consumer": "AIE GEMM/CONV -> PL sv_gate", "format": "int16 codes (formats from the export)"},
    {"name": "W_K", "role": "fragment key projection for the forecast logits", "shape": "[C, D_K]", "consumer": "AIE GEMM", "format": "int8 + shift"},
    {"name": "U", "role": "band-descriptor compatibility map (dot(U nu_f, U nu_g))", "shape": "[J, D_U]", "consumer": "AIE GEMM", "format": "int8 + shift"},
    {"name": "u0", "role": "null (abstention) logit vector", "shape": "[J]", "consumer": "AIE GEMM", "format": "int8"},
    {"name": "u_alpha", "role": "forecast shrink gate vector (alpha = (1 - 2^-4) sigmoid(u_alpha . nu))", "shape": "[J]", "consumer": "AIE GEMM", "format": "int8"},
    {"name": "O_F", "role": "value/output map of the forecast innovation", "shape": "[C, Ct]", "consumer": "AIE GEMM", "format": "int8 + shift"},
    {"name": "Z_l", "role": "per-level residual projection joining the class band only (Prop. 5)", "shape": "[Ct, C] per level", "consumer": "AIE GEMM (int16 x int8)", "format": "int8 + RZ shift"},
    {"name": "trust_heads", "role": "need, rho and Phi producers of the trust QP (Eq. (2)); Phi must be available before the solve", "shape": "[C] / [C] / [C, 4]", "consumer": "AIE GEMM -> PL sv_exchange1", "format": "Q8.23 after scaling"},
    {"name": "class_head", "role": "class-band readout weights", "shape": "[C, classes]", "consumer": "AIE GEMM + HEAD SCORE", "format": "int8 + shift"},
    {"name": "backbone_and_neck_layers", "role": "YOLO26 backbone/neck convolutions with their integer scales and requantization sites", "shape": "per layer", "consumer": "AIE CONV/GEMM units", "format": "int8 weights, int32 bias, per-channel shifts"},
]


def build() -> dict:
    m = load_manifest(REPO / "contracts" / "manifest.dev.json")
    dec = m.get("decisions", {})
    items = []
    for path, d in sorted(dec.items(), key=lambda kv: (kv[1].get("id", ""), kv[0])):
        source = "trained model / calibration (replace)" if d.get("kind") == "synthetic" else "model source (confirm or replace)"
        items.append({"manifest_field": path, "now": d.get("id"), "kind": d.get("kind"), "source": source, "why": d.get("why", "")})
    for path in null_fields(m):
        items.append({"manifest_field": path, "now": "null", "kind": "unresolved", "source": "model export (required)",
                      "why": "the paper does not give it; deployment is refused while it is null"})
    return {
        "_doc": "Generated by tools/make_export_spec.py from contracts/manifest.dev.json. The trained SPLICE detector export "
                "(contracts/manifest.model.json + checkpoint tensors) must supply every item below; tools/check_contract.py "
                "--require-deployable then decides deployability.",
        "dev_manifest_sha256": manifest_sha256(m),
        "model_versions": {
            "Dpub": "published detector (comparator for P7)",
            "DFP32": "arm (e) in float32 with the revised readout and gated forecast",
            "Db": "DFP32 with the bounded algorithms (counted linkage budget, caps, screened QP) - diagnostic step",
            "M": "the integer-manifest model executed by reference/splicev_ref (P2 compares DFP32 to M)",
            "H": "the hardware execution of M on the VE2302 (P1: bit-identical to M at the six boundaries)",
        },
        "artifact_inventory": ["model source and exact commit", "trained checkpoint(s) with hashes", "export graph and per-layer inventory",
                               "preprocessing", "class ordering", "calibration split definition and hashes", "metric implementation"],
        "tensors": TENSORS,
        "manifest_fields": items,
    }


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    text = json.dumps(build(), indent=2) + "\n"
    if a.check:
        if not OUT.exists() or OUT.read_text() != text:
            print(f"{OUT} is stale: run python3 tools/make_export_spec.py")
            return 1
        print(f"{OUT} is current")
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text)
    print(OUT)
    return 0


if __name__ == "__main__":
    sys.exit(main())
